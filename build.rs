use shadow_rs::ShadowBuilder;

fn main() {
    ShadowBuilder::builder()
        .deny_const(Default::default())
        .build()
        .expect("shadow build");

    let unix = cfg!(unix);
    let macos = cfg!(target_os = "macos");

    let layer_shell_capture = cfg!(feature = "layer_shell_capture");
    let libei_capture = cfg!(feature = "libei_capture");
    let x11_capture = cfg!(feature = "x11_capture");

    let libei_emulation = cfg!(feature = "libei_emulation");
    let x11_emulation = cfg!(feature = "x11_emulation");
    let wlroots_emulation = cfg!(feature = "wlroots_emulation");
    let rdp_emulation = cfg!(feature = "rdp_emulation");

    let layer_shell_capture = unix && !macos && layer_shell_capture;
    let libei_capture = unix && !macos && libei_capture;
    let x11_capture = unix && !macos && x11_capture;

    let libei_emulation = unix && !macos && libei_emulation;
    let rdp_emulation = unix && !macos && rdp_emulation;
    let wlroots_emulation = unix && !macos && wlroots_emulation;
    let x11_emulation = unix && !macos && x11_emulation;

    println!("cargo::rustc-check-cfg=cfg(layer_shell_capture)");
    println!("cargo::rustc-check-cfg=cfg(libei_capture)");
    println!("cargo::rustc-check-cfg=cfg(x11_capture)");

    println!("cargo::rustc-check-cfg=cfg(libei_emulation)");
    println!("cargo::rustc-check-cfg=cfg(rdp_emulation)");
    println!("cargo::rustc-check-cfg=cfg(wlroots_emulation)");
    println!("cargo::rustc-check-cfg=cfg(x11_emulation)");

    if layer_shell_capture {
        println!("cargo::rustc-cfg=layer_shell_capture");
    }
    if libei_capture {
        println!("cargo::rustc-cfg=libei_capture");
    }
    if x11_capture {
        println!("cargo::rustc-cfg=x11_capture");
    }

    if libei_emulation {
        println!("cargo::rustc-cfg=libei_emulation");
    }
    if rdp_emulation {
        println!("cargo::rustc-cfg=rdp_emulation");
    }
    if wlroots_emulation {
        println!("cargo::rustc-cfg=wlroots_emulation");
    }
    if x11_emulation {
        println!("cargo::rustc-cfg=x11_emulation");
    }

    // compile the translations into a plain lookup table: platforms differ a
    // lot in how (and whether) their intl library loads catalogues, a
    // generated table behaves the same everywhere (see po/)
    println!("cargo:rerun-if-changed=po");
    if let Ok(entries) = std::fs::read_dir("po") {
        for entry in entries.flatten() {
            println!("cargo:rerun-if-changed={}", entry.path().display());
        }
    }
    compile_catalogues();
}

/// entries of a `.po` file as (msgid, msgstr) pairs
fn read_po(text: &str) -> Vec<(String, String)> {
    let unquote = |line: &str| -> String {
        line.trim()
            .trim_start_matches('"')
            .trim_end_matches('"')
            .replace("\\n", "\n")
            .replace("\\\"", "\"")
            .replace("\\\\", "\\")
    };
    let mut entries = vec![];
    let mut msgid: Option<String> = None;
    let mut msgstr: Option<String> = None;
    let mut in_msgstr = false;
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(rest) = line.strip_prefix("msgid ") {
            if let (Some(id), Some(translated)) = (msgid.take(), msgstr.take()) {
                if !id.is_empty() && !translated.is_empty() {
                    entries.push((id, translated));
                }
            }
            msgid = Some(unquote(rest));
            in_msgstr = false;
        } else if let Some(rest) = line.strip_prefix("msgstr ") {
            msgstr = Some(unquote(rest));
            in_msgstr = true;
        } else if line.starts_with('"') {
            let part = unquote(line);
            match (in_msgstr, msgstr.as_mut(), msgid.as_mut()) {
                (true, Some(text), _) => text.push_str(&part),
                (false, _, Some(id)) => id.push_str(&part),
                _ => {}
            }
        }
    }
    if let (Some(id), Some(translated)) = (msgid, msgstr) {
        if !id.is_empty() && !translated.is_empty() {
            entries.push((id, translated));
        }
    }
    entries
}

/// write `src/i18n/catalogues.rs` with one table per language
fn compile_catalogues() {
    let mut out = String::from("// generated by build.rs from po/*.po, do not edit\n");
    out.push_str("pub static CATALOGUES: &[(&str, &[(&str, &str)])] = &[\n");
    let mut languages: Vec<_> = std::fs::read_dir("po")
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|e| {
            let path = e.path();
            let language = path.file_stem()?.to_string_lossy().into_owned();
            (path.extension()? == "po").then_some((language, path))
        })
        .collect();
    languages.sort();
    for (language, path) in languages {
        let text = std::fs::read_to_string(&path).unwrap_or_default();
        out.push_str(&format!("    (\"{language}\", &[\n"));
        for (id, translated) in read_po(&text) {
            out.push_str(&format!("        ({:?}, {:?}),\n", id, translated));
        }
        out.push_str("    ]),\n");
    }
    out.push_str("];\n");
    let dir = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("catalogues.rs");
    std::fs::write(dir, out).expect("write catalogues");
}
