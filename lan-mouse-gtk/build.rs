//! Compiles the bundled resources and the translated copies of the `.ui`
//! templates.
//!
//! The texts of a template never pass through `gettext`: GTK builds each
//! template from its XML at run time. So every translatable text is replaced
//! here, once per language of `po/*.po`, and the results are registered by
//! `run()` under the path the `#[template]` attributes use. The bundled
//! `lan-mouse.gresource` is registered first and the selected language's
//! templates are placed on top of it.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

fn main() {
    // the paths are relative to this manifest; a directory does not track its
    // files, they are named one by one
    println!("cargo:rerun-if-changed=build.rs");
    for dir in ["resources", "../po"] {
        for entry in std::fs::read_dir(dir).into_iter().flatten().flatten() {
            let path = entry.path();
            if path.is_dir() {
                for entry in std::fs::read_dir(&path).into_iter().flatten().flatten() {
                    println!("cargo:rerun-if-changed={}", entry.path().display());
                }
            } else {
                println!("cargo:rerun-if-changed={}", path.display());
            }
        }
    }

    compile_resources("lan-mouse.gresource");

    if cfg!(feature = "i18n") {
        compile_templates();
    }
}

/// the resource bundle as `glib-compile-resources` builds it
fn compile_resources(target: &str) {
    // glib_build_tools runs the tool in the current directory
    glib_build_tools::compile_resources(
        &["resources"],
        "resources/resources.gresource.xml",
        target,
    );
}

fn manifest_dir() -> PathBuf {
    PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"))
}

fn root_dir() -> PathBuf {
    manifest_dir().parent().expect("workspace root").to_owned()
}

/// writes `translated-<language>.gresource` with the `.ui` files of
/// `resources/` translated with `po/<language>.po`
fn compile_templates() {
    let root = root_dir();
    let po_dir = root.join("po");
    let mut languages: Vec<(String, PathBuf)> = std::fs::read_dir(&po_dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| {
            let path = entry.path();
            let language = path.file_stem()?.to_string_lossy().into_owned();
            (path.extension()? == "po").then_some((language, path))
        })
        .collect();
    languages.sort();
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let templates = ui_files();
    for (language, _) in &languages {
        translated_resources(&out_dir, language, &templates);
    }

    let mut index = String::from("// generated by build.rs from po/*.po, do not edit\n");
    index.push_str("/// (language, compiled templates) for every language of po/\n");
    index.push_str("pub static UI_BUNDLES: &[(&str, &[u8])] = &[\n");
    for (language, _) in &languages {
        index.push_str(&format!(
            "    (\"{language}\", include_bytes!(concat!(env!(\"OUT_DIR\"), \"/translated-{language}.gresource\"))),\n"
        ));
    }
    index.push_str("];\n");
    let dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("ui_translations.rs");
    std::fs::write(dir, index).expect("write ui translations");
}

fn ui_files() -> Vec<(String, Vec<u8>)> {
    let dir = manifest_dir().join("resources");
    let mut files: Vec<(String, Vec<u8>)> = std::fs::read_dir(&dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| {
            let path = entry.path();
            (path.extension()? == "ui").then_some(path)
        })
        .filter_map(|path| {
            let name = path.file_name()?.to_string_lossy().into_owned();
            Some((name, std::fs::read(&path).ok()?))
        })
        .collect();
    files.sort();
    files
}

fn translated_resources(out_dir: &Path, language: &str, templates: &[(String, Vec<u8>)]) {
    let po = std::fs::read_to_string(root_dir().join("po").join(format!("{language}.po")))
        .unwrap_or_default();
    let translations: HashMap<String, String> = read_po(&po).into_iter().collect();
    let generic: HashMap<String, String> = {
        let base = language.split('_').next().unwrap_or(language);
        if base == language {
            HashMap::new()
        } else {
            let text = std::fs::read_to_string(root_dir().join("po").join(format!("{base}.po")))
                .unwrap_or_default();
            read_po(&text).into_iter().collect()
        }
    };
    let translate = |text: &str| -> Option<String> {
        translations
            .get(text)
            .or_else(|| generic.get(text))
            .cloned()
    };

    // a copy of the manifest with the translated templates and the resource
    // names the library registers
    let work = out_dir.join(format!("translated-{language}"));
    let _ = std::fs::remove_dir_all(&work);
    std::fs::create_dir_all(&work).expect("work dir");
    let mut manifest = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<gresources>\n  <gresource prefix=\"/de/feschber/LanMouse\">\n",
    );
    for (name, data) in templates {
        let text = String::from_utf8_lossy(data);
        let translated = translate_ui(&text, &translate);

        std::fs::write(work.join(name), translated).expect("write template");
        manifest.push_str(&format!(
            "    <file compressed=\"true\" preprocess=\"xml-stripblanks\">{name}</file>\n"
        ));
    }
    manifest.push_str("  </gresource>\n</gresources>\n");
    std::fs::write(work.join("resources.gresource.xml"), manifest).expect("write manifest");
    let status = std::process::Command::new("glib-compile-resources")
        .arg("--sourcedir")
        .arg(&work)
        .arg("--target")
        .arg(out_dir.join(format!("translated-{language}.gresource")))
        .arg(work.join("resources.gresource.xml"))
        .status()
        .expect("glib-compile-resources not found");
    assert!(
        status.success(),
        "glib-compile-resources failed for {language}"
    );
    let _ = std::fs::remove_dir_all(&work);
}

/// replaces the text of every element whose start tag has
/// `translatable="yes"`. The templates use no context and no plurals, so the
/// text is exactly what stands between the start tag and the next `<`.
fn translate_ui(text: &str, translate: &dyn Fn(&str) -> Option<String>) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    loop {
        // the next construct: a comment, a declaration (`<?xml ...?>`,
        // `<!DOCTYPE ...>`) or a tag; everything in front of it is text
        let Some(lt) = rest.find('<') else {
            out.push_str(rest);
            break;
        };
        out.push_str(&rest[..lt]);
        rest = &rest[lt..];
        let end = if rest.starts_with("<!--") {
            rest.find("-->").map(|i| i + 3)
        } else {
            rest.find('>').map(|i| i + 1)
        };
        let Some(end) = end else {
            out.push_str(rest);
            break;
        };
        let tag = &rest[..end];
        out.push_str(tag);
        rest = &rest[end..];
        let translatable = !tag.starts_with("</")
            && !tag.starts_with("<!--")
            && !tag.starts_with("<?")
            && !tag.starts_with("<!")
            && tag.contains("translatable=\"yes\"");
        if translatable {
            let end = rest.find('<').unwrap_or(rest.len());
            // markup texts are escaped in the file, the strings are not
            // markup escapes the ampersand twice: `&#38;amp;` is `&amp;` for
            // the parser
            let escaped = xml_unescape(&rest[..end].replace("&#38;", "&"));
            match translate(&escaped) {
                Some(translated) => out.push_str(&xml_escape(&translated)),
                None => out.push_str(&rest[..end]),
            }
            rest = &rest[end..];
        }
    }
    out
}

/// entries of a `.po` file as (msgid, msgstr) pairs
fn read_po(text: &str) -> Vec<(String, String)> {
    let unquote = |line: &str| -> String {
        line.trim()
            .trim_start_matches('"')
            .trim_end_matches('"')
            .replace("\\n", "\n")
            .replace("\\\"", "\"")
            .replace("\\\\", "\\")
    };
    let mut entries = vec![];
    let mut msgid: Option<String> = None;
    let mut msgstr: Option<String> = None;
    let mut in_msgstr = false;
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(rest) = line.strip_prefix("msgid ") {
            if let (Some(id), Some(translated)) = (msgid.take(), msgstr.take()) {
                if !id.is_empty() && !translated.is_empty() {
                    entries.push((id, translated));
                }
            }
            msgid = Some(unquote(rest));
            in_msgstr = false;
        } else if let Some(rest) = line.strip_prefix("msgstr ") {
            msgstr = Some(unquote(rest));
            in_msgstr = true;
        } else if line.starts_with('"') {
            let part = unquote(line);
            match (in_msgstr, msgstr.as_mut(), msgid.as_mut()) {
                (true, Some(text), _) => text.push_str(&part),
                (false, _, Some(id)) => id.push_str(&part),
                _ => {}
            }
        }
    }
    if let (Some(id), Some(translated)) = (msgid, msgstr) {
        if !id.is_empty() && !translated.is_empty() {
            entries.push((id, translated));
        }
    }
    entries
}

/// the text of an element as the XML parser reads it
fn xml_unescape(text: &str) -> String {
    if !text.contains('&') {
        return text.to_owned();
    }
    text.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}

/// the text as it is written into the XML file
fn xml_escape(text: &str) -> String {
    if !text.contains(['<', '>', '&', '"', '\'']) {
        return text.to_owned();
    }
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}
